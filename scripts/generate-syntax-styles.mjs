import theme from '@shikijs/themes/github-light';
import { writeFileSync, readFileSync } from 'node:fs';
const colors = [...new Set([theme.colors['editor.foreground'], ...theme.tokenColors.map(t => t.settings.foreground)].filter(Boolean).map(c => c.toLowerCase()))].sort();
const luminance = hex => {
  const rgb=hex.slice(1).match(/../g).map(x=>parseInt(x,16)/255).map(x=>x<=.04045?x/12.92:((x+.055)/1.055)**2.4);
  return rgb[0]*.2126+rgb[1]*.7152+rgb[2]*.0722;
};
const backgrounds=['#f4f2f7','#edf7ef','#fff0ef'];
const readable = color => {
  let rgb=color.slice(1).match(/../g).map(x=>parseInt(x,16));
  for(let n=0;n<100;n++) {
    const hex='#'+rgb.map(x=>x.toString(16).padStart(2,'0')).join('');
    if(backgrounds.every(bg=>(luminance(bg)+.05)/(luminance(hex)+.05)>=4.5))return hex;
    rgb=rgb.map(x=>Math.floor(x*.95));
  }
  return '#24292e';
};
const rules = colors.map((c,i)=>`.syntax .syn-c${i}{color:${readable(c)}}`).join('\n') + '\n' + [1,2,3,4,5,6,7].map(n=>`.syntax .syn-f${n}{${n&1?'font-style:italic;':''}${n&2?'font-weight:700;':''}${n&4?'text-decoration:underline;':''}}`).join('\n') + '\n.syntax .syn-add{background:#edf7ef}.syntax .syn-del{background:#fff0ef}\n';
const files = {
 'src/presentation/syntax/palette.ts': '// Generated by scripts/generate-syntax-styles.mjs from github-light 4.4.3.\nexport const colors = '+JSON.stringify(colors)+';\nexport const syntaxCss = '+JSON.stringify(rules)+';\n',
 'src/web/styles/syntax.css': '/* Generated from github-light 4.4.3. */\n'+rules,
};
for(const [path,content] of Object.entries(files)) {
 if(process.argv.includes('--check')) { if(readFileSync(path,'utf8')!==content) throw Error(`Stale syntax palette: ${path}`); }
 else writeFileSync(path,content);
}
